import fs from 'node:fs';
import assert from 'node:assert/strict';
import ts from '../frontend/node_modules/typescript/lib/typescript.js';
import * as THREE from '../frontend/node_modules/three/build/three.module.js';
const three=new URL('../frontend/node_modules/three/build/three.module.js',import.meta.url).href;
const source=fs.readFileSync(new URL('../frontend/src/avatarPlayback.ts',import.meta.url),'utf8').replace("'three'",JSON.stringify(three));
const code=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {AvatarPlayback}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const model=new THREE.Object3D();model.name='body';model.position.x=7;
const mixer=new THREE.AnimationMixer(model),player=new AvatarPlayback(mixer);
const clip=new THREE.AnimationClip('first',2,[new THREE.NumberKeyframeTrack('.position[x]',[0,2],[0,2])]);
const second=new THREE.AnimationClip('second',1,[new THREE.NumberKeyframeTrack('.position[x]',[0,1],[10,20])]);
let resets=0;const stop=mixer.stopAllAction.bind(mixer);mixer.stopAllAction=()=>{resets++;return stop()};
player.sample(clip,.5);assert.equal(model.position.x,.5);
player.sample(clip,1.5);assert.equal(model.position.x,1.5);assert.equal(resets,1);
player.sample(clip,.25);assert.equal(model.position.x,.25);assert.equal(resets,1);
player.sample(clip,2);assert.equal(model.position.x,2);
player.sample(clip,0);assert.equal(model.position.x,0);
player.sample(null);assert.equal(model.position.x,7);
player.sample(null);assert.equal(resets,2);
player.sample(second,.5);assert.equal(model.position.x,15);
player.sample(clip,1);assert.equal(model.position.x,1);
player.dispose();assert.equal(model.position.x,7);
const idle=new THREE.AnimationClip('idle',1,[new THREE.NumberKeyframeTrack('.position[x]',[0,1],[3,3])]);
const withIdle=new AvatarPlayback(mixer,idle);
withIdle.sample(null);assert.equal(model.position.x,3);
withIdle.transition({clip,time:1},null,.5);assert.equal(model.position.x,2);
withIdle.transition({clip,time:1},{clip:second,time:.5},.25);assert.equal(model.position.x,4.5);
withIdle.transition({clip,time:1},null,.5);assert.equal(model.position.x,2);
withIdle.sample(clip,1);assert.equal(model.position.x,1);
withIdle.dispose();assert.equal(model.position.x,7);
console.log('Avatar playback: forward/backward seeking, final frame, replay, gap/restoration and clip switching passed; no per-frame action reset.');
